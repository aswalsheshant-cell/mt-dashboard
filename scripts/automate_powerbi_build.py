expense_pct = 0.15
cm2_pct = ((1 - tot_pct - expense_pct) * 100)

print(f"  Total NSV:       {total_nsv_cr:.1f} Crore")
print(f"  YoY Growth:      {yoy_growth_pct:.1f}%")
print(f"  Total Stores:    {total_stores}")
print(f"  CM2% (approx):   {cm2_pct:.1f}%")
print(f"  Avg TOT%:        {tot_pct*100:.1f}%")

